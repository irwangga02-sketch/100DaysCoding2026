public class Day17 {
    
    public static void main(String[] args) {
        int nilaiAwal = 5;
        System.out.println("nilai Awal : "+ nilaiAwal);
      
        nilaiAwal += 10;
        System.out.println("hasil += 10 : "+ nilaiAwal);
        
        nilaiAwal -= 1;
        System.out.println("hasil -= 1 : "+ nilaiAwal);
        
        nilaiAwal *= 2;
        System.out.println("hasil *= 2 : "+ nilaiAwal);
        
        nilaiAwal /= 4;
        System.out.println("hasil /= 4 : "+ nilaiAwal);
        
        nilaiAwal %= 2;
        System.out.println("hasil %= 2 : "+ nilaiAwal);
    }
    
}
